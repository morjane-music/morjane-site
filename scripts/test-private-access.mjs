import assert from "node:assert/strict";
import { createHmac } from "node:crypto";
import { readFileSync } from "node:fs";
import { hashPrivatePassword, verifyPrivatePassword } from "../netlify/functions/_shared/private-access-password.mjs";
import { createPrivateAccessToken, verifyPrivateAccessToken } from "../netlify/functions/_shared/private-access-session.mjs";
import { createSetAuthHandler } from "../netlify/functions/set-auth.mts";
