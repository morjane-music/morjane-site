const user = { id: "00000000-0000-4000-8000-000000000001", email: "admin@example.test" };
const fakeClient = (role) => ({ from: () => ({ select: () => ({ eq: () => ({ maybeSingle: async () => ({ data: { id: user.id, role }, error: null }) }) }) }) });
const cfg = { supabaseUrl: "https://test.supabase.co", anonKey: "anon", serviceRoleKey: "role", adminCookieSecret: "admin-gate-secret" };
const fakeAuth = { auth: { getUser: async () => ({ data: { user }, error: null }) } };
let auth = await authenticatePrivateAccessAdmin(new Request("https://morjane.re/api/admin-private-access"), cfg, { authClient: fakeAuth, adminClient: fakeClient("admin") });
assert.equal(auth.ok, false, "unauthenticated admin request refused");
auth = await authenticatePrivateAccessAdmin(new Request("https://morjane.re/api/admin-private-access", { headers: { Authorization: "Bearer token" } }), cfg, { authClient: fakeAuth, adminClient: fakeClient("member") });
assert.equal(auth.error, "forbidden", "non-admin refused");
auth = await authenticatePrivateAccessAdmin(new Request("https://morjane.re/api/admin-private-access", { headers: { Authorization: "Bearer token" } }), cfg, { authClient: fakeAuth, adminClient: fakeClient("admin") });
assert.equal(auth.error, "admin_gate_required", "admin without PIN gate refused");
const payload = Buffer.from(JSON.stringify({ v: 1, uid: user.id, exp: Math.floor(Date.now() / 1000) + 60 })).toString("base64url");
const signature = createHmac("sha256", cfg.adminCookieSecret).update(payload).digest("base64url");
auth = await authenticatePrivateAccessAdmin(new Request("https://morjane.re/api/admin-private-access", { headers: { Authorization: "Bearer token", Cookie: `atelier_admin_gate=${payload}.${signature}` } }), cfg, { authClient: fakeAuth, adminClient: fakeClient("admin") });
assert.equal(auth.ok, true, "real server admin chain accepted");

