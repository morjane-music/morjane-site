const password = "mot-de-passe-test-solide";
const signer = "cookie-secret-independent-test-only";
const hash = await hashPrivatePassword(password);
assert.match(hash, /^scrypt\$32768\$8\$1\$/);
assert.equal(await verifyPrivatePassword(password, hash), true);
assert.equal(await verifyPrivatePassword("mauvais-mot-de-passe", hash), false);

const now = Date.parse("2026-09-09T10:00:00Z");
const token = await createPrivateAccessToken("set", 4, signer, now);
assert.equal(await verifyPrivateAccessToken(token, "set", 4, signer, now), true);
assert.equal(await verifyPrivateAccessToken(`${token}x`, "set", 4, signer, now), false);
assert.equal(await verifyPrivateAccessToken(token, "set", 3, signer, now), false);
assert.equal(await verifyPrivateAccessToken(token, "set", 4, signer, now + (4 * 60 * 60 + 1) * 1000), false);
const grantToken = await createPrivateAccessToken("set", 7, signer, Date.now(), "00000000-0000-4000-8000-000000000077");
assert.doesNotMatch(grantToken, /@|example|scrypt|mot-de-passe/i);

let credential = { status: "configured", credential: { enabled: true, password_hash: hash, session_version: 4 } };
let rateAllowed = true;
const store = { registerAttempt: async () => rateAllowed, clearAttempts: async () => {}, getCredential: async () => credential };
const handler = createSetAuthHandler({ cookieSecret: signer, serviceRoleKey: "role", supabaseUrl: "https://test.supabase.co", store });
const request = (submitted) => new Request("https://morjane.re/api/set-auth", { method: "POST", headers: { Origin: "https://morjane.re", "Content-Type": "application/x-www-form-urlencoded" }, body: new URLSearchParams({ password: submitted }) });
let response = await handler(request("incorrect"), { ip: "192.0.2.1" });
assert.equal(response.headers.get("location"), "/set-access?error=invalid");
response = await handler(request(password), { ip: "192.0.2.1" });
assert.equal(response.headers.get("location"), "/set");
const sharedCookie = response.headers.get("set-cookie")?.split(";")[0] || "";
assert.match(response.headers.get("set-cookie"), /HttpOnly/);
assert.match(response.headers.get("set-cookie"), /SameSite=Strict/);
assert.doesNotMatch(response.headers.get("set-cookie"), /mot-de-passe|scrypt|email/i);
rateAllowed = false;
response = await handler(request(password), { ip: "192.0.2.1" });
assert.equal(response.headers.get("location"), "/set-access?error=invalid");
credential = { status: "error" };
rateAllowed = true;
response = await handler(request(password), { ip: "192.0.2.1" });
assert.equal(response.headers.get("location"), "/set-access?error=invalid");

credential = { status: "configured", credential: { enabled: true, password_hash: hash, session_version: 5 } };
const rpcVersion5 = async (_url, _key, name) => name === "private_access_get_state" ? [{ configured: true, enabled: true, session_version: 5 }] : [];
const protectSet = createSetProtector({ supabaseUrl: "https://test.supabase.co", anonKey: "anon", cookieSecret: signer, rpc: rpcVersion5 });
response = await protectSet(new Request("https://morjane.re/set", { headers: { Cookie: sharedCookie } }), { next: async () => new Response("private") });
assert.equal(response.status, 303, "an old session_version must be rejected after revocation/password change");
response = await protectSet(new Request("https://morjane.re/assets/set-private/Cosmos.mp3"), { next: async () => new Response("private") });
assert.equal(response.status, 404);
const protectActe = createActe1Protector({ supabaseUrl: "https://test.supabase.co", anonKey: "anon", cookieSecret: signer, rpc: async () => [{ configured: true, enabled: true, session_version: 1 }] });
